pub struct Buffer {
    pub b: [u8; 256],
    pub n: usize,
}
impl Buffer {
    pub const fn new() -> Self {
        Self { b: [0; 256], n: 0 }
    }
    pub fn add(&mut self, v: &[u8]) {
        let n = v.len().min(256 - self.n);
        self.b[self.n..self.n + n].copy_from_slice(&v[..n]);
        self.n += n;
    }
    pub fn num(&mut self, mut v: usize) {
        let mut a = [0; 20];
        let mut i = 20;
        loop {
            i -= 1;
            a[i] = b'0' + (v % 10) as u8;
            v /= 10;
            if v == 0 {
                break;
            }
        }
        self.add(&a[i..]);
    }
    pub fn bytes(&self) -> &[u8] {
        &self.b[..self.n]
    }
}
